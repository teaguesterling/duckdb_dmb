#!/usr/bin/env python3
"""Check strict parity over the round-trip corpus, and write test/sql/dcs_roundtrip_strict.test.

For every sheet in test/data/roundtrip_sheets.csv and every document of test/sql/dcs_roundtrip.test, run
strict dcs_apply three ways: the text, dcs_sheet(text), and dcs_format(dcs_sheet(text)). The spec asks for
the same strict outcome unless the text's first diagnostic is text-level (it stays with the text):

- text succeeds: the DCS value and the formatted text succeed;
- text fails with a rule-level diagnostic: the DCS value fails with the same message, line and column
  included; the formatted text fails with the same code (its lines and columns are its own).

Any other difference stops this script with a list. The cases that fail are written as statement error
pairs, so the unittest runner checks them on every platform.

    test/data/collect_strict.py path/to/duckdb path/to/dmb.duckdb_extension
"""
import csv
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
ERROR = re.compile(r"Error: (dcs_apply: ([a-z-]+) at line \d+, column \d+: .*)$")

# The first diagnostic is text-level (sheet_parser.cpp emits it, and dcs_sheet drops it).
TEXT_LEVEL_CODES = {"nested-rule", "unsupported-at-rule", "unsupported-media", "nested-media"}
TEXT_LEVEL_MESSAGES = ("@import is not supported", "this at-rule is not supported", "@frontmatter inside @media",
                       "cannot parse declaration", "cannot parse rule", "cannot parse: ", "a declaration outside",
                       "@frontmatter needs", "parentheses or brackets nested")


def prelude():
    """The statement-ok blocks of dcs_roundtrip.test that build its documents."""
    text = (ROOT / "test" / "sql" / "dcs_roundtrip.test").read_text()
    out = []
    for block in text.split("\n\n"):
        lines = [l for l in block.splitlines() if not l.startswith("#")]
        if lines and lines[0] == "statement ok" and "read_csv" not in block and "MACRO changes" not in block:
            out.append("\n".join(lines[1:]) + ";")
    return "\n".join(out)


def quote(s):
    return "'" + s.replace("'", "''") + "'"


def run(duckdb, ext, setup, expr, doc):
    sql = "LOAD '%s';\n%s\nSELECT %s IS NOT NULL FROM docs WHERE name = '%s';" % (ext, setup, expr, doc)
    out = subprocess.run([duckdb, "-no-agent", "-unsigned", "-noheader", "-list", "-c", sql],
                         capture_output=True, text=True)
    for line in (out.stdout + out.stderr).splitlines():
        m = ERROR.search(line)
        if m:
            return m.group(1), m.group(2)
    if out.returncode != 0:
        raise SystemExit("unexpected failure for %s on %s:\n%s" % (expr, doc, out.stderr))
    return None, None


def text_level(message, code):
    return code in TEXT_LEVEL_CODES or any(m in message for m in TEXT_LEVEL_MESSAGES)


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    duckdb, ext = sys.argv[1], sys.argv[2]
    setup = prelude()
    with (ROOT / "test" / "data" / "roundtrip_sheets.csv").open() as f:
        sheets = [row["sheet"] for row in csv.DictReader(f)]
    cases, problems, skipped, ok = [], [], 0, 0
    for sheet in sheets:
        q = quote(sheet)
        for doc in ("fx", "mixed"):
            text = run(duckdb, ext, setup, "dcs_apply(doc, %s, true)" % q, doc)
            dcs = run(duckdb, ext, setup, "dcs_apply(doc, dcs_sheet(%s), true)" % q, doc)
            fmt = run(duckdb, ext, setup, "dcs_apply(doc, dcs_format(dcs_sheet(%s)), true)" % q, doc)
            if text[0] is None:
                if dcs[0] or fmt[0]:
                    problems.append((sheet, doc, "text succeeds", dcs[0], fmt[0]))
                ok += 1
            elif text_level(*text):
                skipped += 1
            elif dcs[0] != text[0] or fmt[1] != text[1]:
                problems.append((sheet, doc, text[0], dcs[0], fmt[0]))
            else:
                cases.append((sheet, doc, text[0], text[1]))
    if problems:
        for p in problems:
            print("DIFFERS: sheet=%r doc=%s\n  text:   %s\n  dcs:    %s\n  format: %s" % p)
        raise SystemExit("%d strict differences that are not text-level" % len(problems))
    write(cases)
    print("%d sheet x doc pairs: %d succeed alike, %d fail alike (written), %d text-level (skipped)"
          % (len(sheets) * 2, ok, len(cases), skipped))


def write(cases):
    out = ["# name: test/sql/dcs_roundtrip_strict.test",
           "# description: strict dcs_apply fails the same way for text, its DCS value, and dcs_format of that",
           "#              value, for every corpus sheet whose first diagnostic is rule-level. GENERATED by",
           "#              test/data/collect_strict.py: do not edit; re-run the script.",
           "# group: [sql]", "", "require dmb", ""]
    for block in prelude().split(";\n"):
        block = block.strip().rstrip(";")
        if block and not block.startswith("LOAD"):
            out += ["statement ok", block + ";", ""]
    for sheet, doc, message, code in cases:
        q = quote(sheet)
        for expr, expected in (("dcs_sheet(%s)" % q, message), ("dcs_format(dcs_sheet(%s))" % q,
                                                               "dcs_apply: %s at line" % code)):
            out += ["statement error",
                    "SELECT dcs_apply(doc, %s, true) FROM docs WHERE name = '%s';" % (expr, doc),
                    "----", expected, ""]
    (ROOT / "test" / "sql" / "dcs_roundtrip_strict.test").write_text("\n".join(out))


if __name__ == "__main__":
    main()
